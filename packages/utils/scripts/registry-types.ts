#!/usr/bin/env node

// Generates TypeScript types for the npm Registry OpenAPI spec (MIT) from
// https://api-docs.npmjs.com — the spec is embedded in the page as
// `__redoc_state.spec.data` (no raw JSON endpoint is published).
// Run from the package that should host the types; usage:
//   sv-addon-registry-types [output.d.ts]
//   default: node_modules/.cache/sv-addon/npm-registry-openapi.d.ts

import fs from 'node:fs'
import path from 'node:path'

import openapiTS, { astToString } from 'openapi-typescript'

const SPEC_URL = 'https://api-docs.npmjs.com'
const STATE_MARKER = 'const __redoc_state = '
const DEFAULT_OUT = 'node_modules/.cache/sv-addon/npm-registry-openapi.d.ts'

const extractSpec = (html: string) => {
	const start = html.indexOf(STATE_MARKER)
	if (start === -1) {
		throw new Error(`__redoc_state not found at ${SPEC_URL} — page structure may have changed`)
	}
	const begin = start + STATE_MARKER.length
	const end = html.indexOf(';\n', begin)
	if (end === -1) throw new Error('could not locate the end of __redoc_state')
	const spec = JSON.parse(html.slice(begin, end))?.spec?.data
	if (!spec?.paths)
		throw new Error('__redoc_state.spec.data missing — page structure may have changed')
	return spec
}

const main = async (): Promise<void> => {
	const out = path.resolve(process.argv[2] ?? DEFAULT_OUT)
	const response = await fetch(SPEC_URL)
	if (!response.ok)
		throw new Error(`GET ${SPEC_URL} failed: ${response.status} ${response.statusText}`)
	const ast = await openapiTS(extractSpec(await response.text()))
	fs.mkdirSync(path.dirname(out), { recursive: true })
	fs.writeFileSync(
		out,
		`// Generated by sv-addon-registry-types from ${SPEC_URL} — do not edit\n${astToString(ast)}`,
	)
	console.log(`generated ${path.relative(process.cwd(), out)}`)
}

main().catch((error: unknown) => {
	console.error(error instanceof Error ? error.message : String(error))
	process.exit(1)
})
